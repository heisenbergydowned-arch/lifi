int main(void)
{

  /* USER CODE BEGIN 1 */
  LdrAdcStatus ldr_status;
  uint32_t now_ms;
  uint32_t selected_t_ms;
  bool rtc_present;
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART1_UART_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */
  Buzzer_Init();
  Button_Init(HAL_GetTick());
  rtc_present = DS1302_Init();
  ldr_status = LdrAdc_Init();
  if (ldr_status != LDR_ADC_OK)
  {
    printf("LDR ADC init failed: %u\r\n", (unsigned int)ldr_status);
    Error_Handler();
  }
  LdrReceiver_Init();
  MessageService_Init(rtc_present);
  if (!ESP8266_Init(DEVICE_ADDRESS, MessageService_GetBootCounter()))
  {
    printf("[NET] USART3 receive start failed; optical receiver continues.\r\n");
  }
  ESP8266_SetTimeHandler(MessageService_SetNetworkTime);
  ESP8266_SetConfigHandler(ApplyProtocolConfig);
  ReceiverDisplay_Init(HAL_GetTick());
  ldr_status = LdrAdc_Start();
  if (ldr_status != LDR_ADC_OK)
  {
    printf("LDR ADC start failed: %u\r\n", (unsigned int)ldr_status);
    Error_Handler();
  }
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    LdrReceiver_Process();
    now_ms = HAL_GetTick();
    if (Button_Poll(now_ms, &selected_t_ms))
    {
      (void)LdrReceiver_SetDotTimeMs(selected_t_ms);
    }
    Buzzer_Process(now_ms);
    ESP8266_Process(now_ms);
    ReceiverDisplay_Process(now_ms);
    __WFI();
  }
  /* USER CODE END 3 */
}

